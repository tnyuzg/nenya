//! The packing embedding φ_2 and its multiplicative homomorphism.
//!
//! Two-level Lagrange embedding from the paper §2.3:
//!
//!   φ_1: R_0² → R_1     a ↦ Σ_{j∈[2]}  a_j · ℓ_j(α)
//!   φ_2: R_0³² → R_2    a ↦ Σ_{i∈[16]} (Σ_{j∈[2]} a_{i,j}·ℓ_j(α)) · ℓ_i(β)
//!
//! `mul_with_quotients` computes the *quotient decomposition* of the product
//! φ_2(a)·φ_2(b) so that
//!
//!   φ_2(a) · φ_2(b)  ==  φ_2(c) + q_1 · v_α + q_2 · v_β
//!
//! where c is the Hadamard product of a and b. This is the "multiplicative
//! homomorphism with quotients" identity that drives the R1CS reduction.
//!
//! Generic over the base-limb width `L` (`u8`/`u16`/`u32`/`u64`); the packing
//! size κ = 32 and the 16×2 layout are fixed by the ring tower and independent
//! of `L`.

use crate::constants::{constants, HasPackingConstants};
use galois_ring::{compute_t1_generic, Gr1, Gr128, Gr4, Limb};

// ---------------------------------------------------------------------------
// φ_1, φ_2
// ---------------------------------------------------------------------------

/// φ_1 in the paper §2.3: pack 2 R_0 elements into one R_1 element using
/// the α-Lagrange basis: `a[0]·ℓ_0(α) + a[1]·ℓ_1(α)`.
#[inline]
pub fn pack_r1<L: HasPackingConstants>(a: [Gr1<L>; 2]) -> Gr4<L> {
    let c = constants::<L>();
    Gr4::from_gr1(a[0]) * c.l_alpha[0] + Gr4::from_gr1(a[1]) * c.l_alpha[1]
}

/// φ_2 in the paper §2.3 acting on a 16×2 matrix view. Each row is
/// `pack_r1`-packed into an R_1 element, then those 16 R_1 elements are
/// combined via the β-Lagrange basis into a single R_2 element.
pub fn pack_r2_matrix<L: HasPackingConstants>(a: [[Gr1<L>; 2]; 16]) -> Gr128<L> {
    let c = constants::<L>();
    let mut acc = Gr128::<L>::ZERO;
    for i in 0..16 {
        let row = pack_r1(a[i]);
        // `row ∈ R_1` lifted and multiplied by the `R_2` constant `ℓ_i(β)`;
        // `mul_by_gr4` does the lift-and-multiply in one shot.
        acc = acc + c.l_beta[i].mul_by_gr4(row);
    }
    acc
}

/// Reshape a flat 32-vector into the 16×2 layout: `m[i][j] = a[2*i + j]`.
#[inline]
pub fn rect_from_flat<L: Limb>(a: &[Gr1<L>; 32]) -> [[Gr1<L>; 2]; 16] {
    let mut m = [[Gr1::<L>::ZERO; 2]; 16];
    for i in 0..16 {
        m[i][0] = a[2 * i];
        m[i][1] = a[2 * i + 1];
    }
    m
}

/// φ_2 on a flat 32-vector laid out in row-major order: `a[2*i + j] = a_{i,j}`.
#[inline]
pub fn pack_r2<L: HasPackingConstants>(a: [Gr1<L>; 32]) -> Gr128<L> {
    pack_r2_matrix(rect_from_flat(&a))
}

/// Left inverse of `pack_r2_matrix`. Used in tests only; not optimized.
///
/// `im(pack_r2)` is a free rank-32 `Z/2^n`-submodule of `R_2`, generated by the
/// 32 Lagrange products `{ ℓ_j(α) · ℓ_i(β) }` — the basis images
/// `{ pack_r2(e_{i,j}) }`. As a `[128, 32]` linear code over `Z/2^n`, `unpack_r2`
/// decodes a codeword `x` to the message `a` solving `M · a = vec(x)` by
/// Gaussian elimination (pivoting on odd, i.e. unit, entries).
pub fn unpack_r2<L: HasPackingConstants>(x: Gr128<L>) -> [[Gr1<L>; 2]; 16] {
    let mut basis_imgs: [Gr128<L>; 32] = [Gr128::<L>::ZERO; 32];
    for n in 0..32 {
        let mut m = [[Gr1::<L>::ZERO; 2]; 16];
        m[n / 2][n % 2] = Gr1::<L>::ONE;
        basis_imgs[n] = pack_r2_matrix(m);
    }

    // Row 4*k + r holds the R_0-coefficient at the (β^k slot, α^r slot) of each
    // basis image in cols 0..32, with the matching coefficient of x in col 32.
    let mut rows: Vec<[L; 33]> = Vec::with_capacity(128);
    for k in 0..32 {
        for r in 0..4 {
            let mut row = [L::ZERO; 33];
            for n in 0..32 {
                row[n] = basis_imgs[n].0[k].0[r];
            }
            row[32] = x.0[k].0[r];
            rows.push(row);
        }
    }

    let mut col = 0;
    let mut pivot_rows: [Option<usize>; 32] = [None; 32];
    for row_idx in 0..rows.len() {
        if col >= 32 {
            break;
        }
        let mut found = None;
        for r in row_idx..rows.len() {
            if rows[r][col].is_odd() {
                found = Some(r);
                break;
            }
        }
        let Some(piv) = found else {
            col += 1;
            continue;
        };
        rows.swap(row_idx, piv);
        let inv = rows[row_idx][col].inv_2adic();
        for c in 0..33 {
            rows[row_idx][c] = rows[row_idx][c].wrapping_mul(inv);
        }
        for r in 0..rows.len() {
            if r == row_idx {
                continue;
            }
            let factor = rows[r][col];
            if factor == L::ZERO {
                continue;
            }
            for c in 0..33 {
                rows[r][c] = rows[r][c].wrapping_sub(factor.wrapping_mul(rows[row_idx][c]));
            }
        }
        pivot_rows[col] = Some(row_idx);
        col += 1;
    }

    let mut out = [[Gr1::<L>::ZERO; 2]; 16];
    for n in 0..32 {
        if let Some(r) = pivot_rows[n] {
            out[n / 2][n % 2] = Gr1(rows[r][32]);
        }
    }
    out
}

// ---------------------------------------------------------------------------
// Multiplicative homomorphism with quotients
// ---------------------------------------------------------------------------

/// Computes (c_phi, q1, q2) such that
///
///   `pack_r2_matrix(a) · pack_r2_matrix(b)  ==  c_phi  +  q1·v_α  +  q2·v_β`
///
/// where `c_phi = pack_r2_matrix(c)` for the Hadamard product `c = a∘b`. The
/// closed-form expressions for q1, q2 come from the paper §2.3.4.
pub fn mul_with_quotients<L: HasPackingConstants>(
    a: [[Gr1<L>; 2]; 16],
    b: [[Gr1<L>; 2]; 16],
) -> (Gr128<L>, Gr128<L>, Gr128<L>) {
    // Hadamard product → c_phi via direct φ_2.
    let mut c = [[Gr1::<L>::ZERO; 2]; 16];
    for i in 0..16 {
        for j in 0..2 {
            c[i][j] = a[i][j] * b[i][j];
        }
    }
    let c_phi = pack_r2_matrix(c);
    let (q1, q2) = mul_with_quotients_only(a, b);
    (c_phi, q1, q2)
}

/// Quotient-only variant of `mul_with_quotients`: skips the `c_phi`
/// computation. Used by the MIMD and general-circuit reductions, where the
/// `Im(φ)` part is reconstructed later as `Â·ŵ - ê`.
pub fn mul_with_quotients_only<L: HasPackingConstants>(
    a: [[Gr1<L>; 2]; 16],
    b: [[Gr1<L>; 2]; 16],
) -> (Gr128<L>, Gr128<L>) {
    let consts = constants::<L>();

    // q_1(β) = Σ_i (Σ_{j,k} a_{i,j} b_{i,k} · q^α_{j,k}(α)) · ℓ_i(β)        [R_2]
    // `q^α_{j,k}(α) · ℓ_i(β)` is witness-independent — preprocessed into
    // `q_alpha_l_beta[i][j][k] ∈ R_2`. The runtime scalar `a_{i,j}·b_{i,k} ∈ R_0`
    // rides through `mul_by_gr1`.
    let mut q1 = Gr128::<L>::ZERO;
    for i in 0..16 {
        for j in 0..2 {
            for k in 0..2 {
                let coef = a[i][j] * b[i][k];
                q1 = q1 + consts.q_alpha_l_beta[i][j][k].mul_by_gr1(coef);
            }
        }
    }

    // q_2(β) = Σ_{i,k} φ_1(a_i) · φ_1(b_k) · q_beta[i][k]  [R_2]
    // Symmetry `q_beta[i][k] = q_beta[k][i]` folds the double-sum into 16
    // diagonal + 120 off-diagonal terms.
    let mut a1: [Gr4<L>; 16] = [Gr4::<L>::ZERO; 16];
    let mut b1: [Gr4<L>; 16] = [Gr4::<L>::ZERO; 16];
    for i in 0..16 {
        a1[i] = pack_r1(a[i]);
        b1[i] = pack_r1(b[i]);
    }
    let mut q2 = Gr128::<L>::ZERO;
    for i in 0..16 {
        let p_diag = a1[i] * b1[i];
        q2 = q2 + consts.q_beta[i][i].mul_by_gr4(p_diag);
        for k in (i + 1)..16 {
            let p_off = a1[i] * b1[k] + a1[k] * b1[i];
            q2 = q2 + consts.q_beta[i][k].mul_by_gr4(p_off);
        }
    }

    (q1, q2)
}

// ---------------------------------------------------------------------------
// ψ : R_2 → R_0^32  (the RMFE unpacking) and the kernel-membership test
// ---------------------------------------------------------------------------
//
// ψ is the *forward* unpacking from the paper §1.2–1.3 (NOT the linear left
// inverse `unpack_r2`, whose kernel is an arbitrary complement). It evaluates
// the bivariate (α, β) representative of `x ∈ R_2` at the 32 Teichmüller points
// `(α ∈ T_0) × (β ∈ T_1)`, where `T_0 = {0, 1}` and `T_1 = { t : t¹⁶ = t } ⊂ R_1`
// (the 16 elements of [`galois_ring::compute_t1_generic`]).
//
// The two layers, on `x = Σ_{k<32} x_k·β^k` with `x_k ∈ R_1`:
//   ψ₁(x) := ( x(t_0), …, x(t_15) ) ∈ R_1^16   (eval the β-polynomial at T_1)
//   ψ₀(g) := ( g(0), g(1) ) ∈ R_0²            (eval the α-polynomial at {0,1})
//   ψ(x)  := ( ψ₀(x(t_i)) )_{i<16} ∈ R_0^32
//
// Key facts (verified by the tests below):
//   * ψ(pack_r2(a)) = a  — left inverse on Im(φ), so `ψ` is the RMFE unpacking.
//   * ψ(x) = 0  ⇔  x ∈ ker ψ.
//   * Both vanishing polynomials die: v_α = α²−α has roots {0,1} = T_0, and
//     v_β = β¹⁶−β vanishes on T_1 (every t_i satisfies t¹⁶=t). Hence every
//     packing error `q₁·v_α + q₂·v_β` (the paper eq. 13) lies in ker ψ — which
//     is exactly what the verifier's free-subspace check relies on to certify
//     `a∘b = c` (a dishonest `ê ∉ ker ψ` ⇒ ψ(ê) = a∘b − c ≠ 0).

/// ψ(x): the RMFE unpacking of `x ∈ R_2`, as the 16×2 grid `[x(t_i, 0), x(t_i, 1)]`.
/// `ψ(pack_r2(a)) = a`; `ψ(x) = 0` iff `x ∈ ker ψ`.
pub fn psi_r2<L: Limb>(x: &Gr128<L>) -> [[Gr1<L>; 2]; 16] {
    psi_r2_with_t1(x, &compute_t1_generic::<L>())
}

/// [`psi_r2`] with a caller-supplied `T_1` (avoids recomputing the 16 Teichmüller
/// lifts when unpacking many elements — e.g. a whole batch of opened columns).
#[inline]
pub fn psi_r2_with_t1<L: Limb>(x: &Gr128<L>, t1: &[Gr4<L>; 16]) -> [[Gr1<L>; 2]; 16] {
    let mut out = [[Gr1::<L>::ZERO; 2]; 16];
    for (i, &ti) in t1.iter().enumerate() {
        // ψ₁: evaluate the β-polynomial Σ_k x_k·β^k at β = t_i (Horner in R_1).
        let mut g = Gr4::<L>::ZERO;
        for k in (0..32).rev() {
            g = g * ti + x.0[k];
        }
        // ψ₀: evaluate the α-polynomial g = Σ_r g_r·α^r at α ∈ {0, 1}.
        let g0 = Gr1(g.0[0]); // g(0) = constant α-coefficient
        let g1 = Gr1(g.0[0]) + Gr1(g.0[1]) + Gr1(g.0[2]) + Gr1(g.0[3]); // g(1) = Σ_r g_r
        out[i] = [g0, g1];
    }
    out
}

/// `true` iff `x ∈ ker ψ` (i.e. `ψ(x) = 0`) — the free-subspace membership test
/// for committed packing errors.
#[inline]
pub fn in_kernel<L: Limb>(x: &Gr128<L>) -> bool {
    in_kernel_with_t1(x, &compute_t1_generic::<L>())
}

/// [`in_kernel`] with a caller-supplied `T_1`. Short-circuits on the first
/// nonzero evaluation, so a violation is usually caught well before all 16
/// β-points are swept.
#[inline]
pub fn in_kernel_with_t1<L: Limb>(x: &Gr128<L>, t1: &[Gr4<L>; 16]) -> bool {
    let zero = Gr1::<L>::ZERO;
    for &ti in t1.iter() {
        let mut g = Gr4::<L>::ZERO;
        for k in (0..32).rev() {
            g = g * ti + x.0[k];
        }
        if Gr1(g.0[0]) != zero {
            return false;
        }
        if Gr1(g.0[0]) + Gr1(g.0[1]) + Gr1(g.0[2]) + Gr1(g.0[3]) != zero {
            return false;
        }
    }
    true
}

#[cfg(test)]
mod psi_tests {
    use super::*;
    use crate::constants::constants;

    /// 16×2 grid of pseudo-random `R_0` values from a seed.
    fn rand_a(seed: u64) -> [[Gr1<u32>; 2]; 16] {
        let mut s = seed | 1;
        let mut next = || {
            s = s
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            Gr1((s >> 32) as u32)
        };
        let mut a = [[Gr1::<u32>::ZERO; 2]; 16];
        for row in a.iter_mut() {
            row[0] = next();
            row[1] = next();
        }
        a
    }

    #[test]
    fn psi_is_left_inverse_of_pack() {
        // ψ(φ(a)) = a for every a — pins ψ as *the* RMFE unpacking on Im(φ).
        for seed in [0x1234, 0xDEAD, 0xBEEF, 0xC0FFEE] {
            let a = rand_a(seed);
            assert_eq!(psi_r2(&pack_r2_matrix(a)), a, "ψ∘φ ≠ id (seed {seed:#x})");
        }
    }

    #[test]
    fn image_is_not_in_kernel() {
        // Im(φ) ∩ ker ψ = {0}: a nonzero packed value is never in the kernel.
        assert!(in_kernel(&Gr128::<u32>::ZERO));
        for seed in [0x5678, 0xABCD, 0x9999] {
            assert!(!in_kernel(&pack_r2_matrix(rand_a(seed))));
        }
    }

    #[test]
    fn vanishing_polys_are_in_kernel() {
        let cst = constants::<u32>();
        assert!(in_kernel(&Gr128::from_gr4(cst.v_alpha)), "v_α ∉ ker ψ");
        assert!(in_kernel(&cst.v_beta), "v_β ∉ ker ψ");
    }

    #[test]
    fn honest_packing_error_in_kernel_corrupted_not() {
        // The core soundness property: φ(a)·φ(b) − φ(c) ∈ ker ψ  ⇔  c = a∘b.
        let a = rand_a(0xA);
        let b = rand_a(0xB);
        let prod = pack_r2_matrix(a) * pack_r2_matrix(b);

        // c = a∘b: the packing error is exactly q₁v_α + q₂v_β ∈ ker ψ.
        let mut c = [[Gr1::<u32>::ZERO; 2]; 16];
        for i in 0..16 {
            for j in 0..2 {
                c[i][j] = a[i][j] * b[i][j];
            }
        }
        let e_honest = prod - pack_r2_matrix(c);
        assert!(in_kernel(&e_honest), "honest error must be in ker ψ");

        // Corrupt one output coordinate ⇒ the error gains an Im(φ) part ⇒ leaves ker ψ.
        let mut c_bad = c;
        c_bad[0][0] = c_bad[0][0] + Gr1(1);
        let e_bad = prod - pack_r2_matrix(c_bad);
        assert!(!in_kernel(&e_bad), "corrupted-output error must leave ker ψ");
    }
}
